import 'package:flutter_test/flutter_test.dart';

import 'package:european_dream/core/domain/enums.dart';
import 'package:european_dream/core/domain/models.dart';
import 'package:european_dream/core/domain/settings.dart';
import 'package:european_dream/core/services/metrics_service.dart';
import 'package:european_dream/core/services/plan_generator.dart';
import 'package:european_dream/core/services/scoring_service.dart';
